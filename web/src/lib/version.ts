// Папка автобэкапа по умолчанию — подставляется в настройки, чтобы не вбивать
// руками. Это подпись для глаз: доступ к папке всё равно даёт только браузер,
// по кнопке «Подтвердить доступ» (File System Access API не разрешает открыть
// путь без явного клика). Путь можно изменить прямо в настройках.
//
// Указывает внутрь СЕМЕЙНОЙ папки Яндекс.Диска намеренно: два человека работают
// под разными аккаунтами на разных компьютерах, и им нужны бэкапы в одном месте.
// Семейная папка видна обоим аккаунтам сразу, без приглашений и настройки прав,
// и решает задачу без единой строчки кода — каждая машина пишет свои файлы, диск
// сводит их вместе. Имена включают аккаунт и дату, поэтому машины никогда не
// пишут в один и тот же файл.
// String.raw, а не обычная строка: в "D:\Yandex.Disk\..." последовательности
// \Y и \C не являются валидными escape-последовательностями, и TypeScript молча
// съедает обратные слэши — в сборку уходило «D:Yandex.DiskСемья❤️CRM-Бэкапы».
export const DEFAULT_BACKUP_PATH = String.raw`D:\Yandex.Disk\Семья❤️\CRM-Бэкапы`
